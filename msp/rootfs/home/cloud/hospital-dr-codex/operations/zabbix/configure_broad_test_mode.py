#!/usr/bin/env python3
"""Reconcile the explicitly opt-in broad Zabbix ChatOps test action.

The test action is separate from the production ``Cloud_Slack_DR_Trigger``
action.  It is disabled unless ``--enable`` is used, matches only the named
test hosts, and uses test-only script media types.  All changes go through
the Zabbix JSON-RPC API; PostgreSQL is never modified.
"""

from __future__ import annotations

import argparse
import json
import sys
from dataclasses import dataclass, field
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

from configure_chatops import (
    ConfigurationError,
    ZabbixClient,
    _copy,
    _filter_signature,
    _operation_for_update,
    _read_env_file,
    _redact,
    _text,
    _writable_user_medias,
    _write_json_atomic,
    load_settings,
)


TEST_ACTION_NAME = "Cloud_Slack_DR_Broad_Test_Mode"
TEST_MEDIA_NAMES = ("Slack DR Test Trigger", "Slack Failback Test")
DEFAULT_TEST_HOSTS = ("web_server", "DB_Server", "Doc_Server", "Zabbix server")
# Zabbix 6 expands ALERT.* here.  The helper extracts Host/Event ID/Event age
# from ALERT.MESSAGE because this installation passes the other macros literally
# when they are separate custom-script parameters.
TEST_EXEC_PARAMS = "__zabbix_test__\n{ALERT.SUBJECT}\n{ALERT.MESSAGE}\n"
TEST_SUBJECT = "[DR TEST MODE][{EVENT.STATUS}] {EVENT.NAME}"
TEST_FAILOVER_MESSAGE = (
    "[DR TEST MODE]\n"
    "Action name: {ACTION.NAME}\n"
    "Event ID: {EVENT.ID}\n"
    "Trigger ID: {TRIGGER.ID}\n"
    "Event source: {EVENT.SOURCE}\n"
    "Host: {HOST.NAME}\n"
    "Status: {EVENT.STATUS}\n"
    "Severity: {EVENT.SEVERITY}\n"
    "Value: {EVENT.VALUE}\n"
    "Event age: {EVENT.AGE}\n"
    "Event tags JSON: {EVENT.TAGSJSON}\n"
    "Time: {EVENT.DATE} {EVENT.TIME}"
)
TEST_FAILBACK_MESSAGE = (
    "[DR TEST MODE]\n"
    "Event ID: {EVENT.ID}\n"
    "Host: {HOST.NAME}\n"
    "Status: {EVENT.STATUS}\n"
    "Severity: {EVENT.SEVERITY}\n"
    "Value: {EVENT.VALUE}\n"
    "Event age: {EVENT.AGE}\n"
    "Time: {EVENT.DATE} {EVENT.TIME}"
)


@dataclass
class Plan:
    changes: list[str] = field(default_factory=list)
    errors: list[str] = field(default_factory=list)
    media_creates: list[dict[str, Any]] = field(default_factory=list)
    media_updates: list[tuple[str, dict[str, Any]]] = field(default_factory=list)
    user_media: list[dict[str, Any]] | None = None
    action_create: dict[str, Any] | None = None
    action_update: tuple[str, dict[str, Any]] | None = None


def _normalise(value: Any) -> Any:
    if isinstance(value, dict):
        return {key: _normalise(item) for key, item in sorted(value.items()) if key not in {"actionid", "operationid"}}
    if isinstance(value, list):
        return [_normalise(item) for item in value]
    return value


def _operation_signature(operation: dict[str, Any]) -> Any:
    return _normalise(_operation_for_update(operation))


def _recovery_operation_signature(operation: dict[str, Any]) -> Any:
    value = _operation_for_update(operation)
    # Zabbix 6 adds these empty/default fields when it reads a recovery
    # operation, although it rejects them in the create payload.
    value.pop("evaltype", None)
    value.pop("opconditions", None)
    return _normalise(value)


def _test_filter_signature(filter_value: dict[str, Any] | None) -> tuple[Any, ...]:
    signature = _filter_signature(filter_value)
    # eval_formula is generated by Zabbix for OR filters and is read-only.
    if _text((filter_value or {}).get("evaltype")) == "2" and not _text(
        (filter_value or {}).get("formula")
    ):
        return (signature[0], "", signature[2], signature[3])
    return signature


def _operation(media_id: str, user_id: str, message: str = TEST_FAILOVER_MESSAGE) -> dict[str, Any]:
    return {
        "operationtype": "0",
        "esc_period": "0",
        "esc_step_from": "1",
        "esc_step_to": "1",
        "evaltype": "0",
        "opconditions": [],
        "opmessage": {
            "default_msg": "0",
            "subject": TEST_SUBJECT,
            "message": message,
            "mediatypeid": media_id,
        },
        "opmessage_grp": [],
        "opmessage_usr": [{"userid": user_id}],
    }


def _recovery_operation(media_id: str, user_id: str, message: str = TEST_FAILBACK_MESSAGE) -> dict[str, Any]:
    return {
        "operationtype": "0",
        "opmessage": {
            "default_msg": "0",
            "subject": TEST_SUBJECT,
            "message": message,
            "mediatypeid": media_id,
        },
        "opmessage_grp": [],
        "opmessage_usr": [{"userid": user_id}],
    }


class BroadTestConfigurator:
    def __init__(self, api: Any, settings: Any, host_names: tuple[str, ...]):
        self.api = api
        self.settings = settings
        self.host_names = host_names

    def inspect(self) -> dict[str, Any]:
        hosts = self.api.call(
            "host.get",
            {
                "output": ["hostid", "host", "name", "status"],
                "filter": {"name": list(self.host_names)},
            },
        )
        media: dict[str, dict[str, Any] | None] = {}
        for name in TEST_MEDIA_NAMES:
            rows = self.api.call(
                "mediatype.get",
                {
                    "output": "extend",
                    "filter": {"name": name},
                },
            )
            matches = [item for item in rows or [] if _text(item.get("name")) == name]
            if len(matches) > 1:
                raise ConfigurationError(f"Multiple media types have the name {name!r}")
            media[name] = matches[0] if matches else None

        users = self.api.call(
            "user.get",
            {
                "output": "extend",
                "filter": {"username": self.settings.recipient_username},
                "selectMedias": "extend",
            },
        )
        users = [item for item in users or [] if _text(item.get("username")) == self.settings.recipient_username]
        if len(users) > 1:
            raise ConfigurationError(
                f"Multiple users have the username {self.settings.recipient_username!r}"
            )

        actions = self.api.call(
            "action.get",
            {
                "output": "extend",
                "filter": {"name": TEST_ACTION_NAME},
                "selectFilter": "extend",
                "selectOperations": "extend",
                "selectRecoveryOperations": "extend",
                "selectUpdateOperations": "extend",
            },
        )
        actions = [item for item in actions or [] if _text(item.get("name")) == TEST_ACTION_NAME]
        if len(actions) > 1:
            raise ConfigurationError(f"Multiple actions have the name {TEST_ACTION_NAME!r}")
        return {
            "hosts": {name: next((item for item in hosts or [] if item.get("name") == name), None) for name in self.host_names},
            "media": media,
            "user": users[0] if users else None,
            "action": actions[0] if actions else None,
        }

    def _media_specs(self) -> dict[str, dict[str, Any]]:
        return {
            "Slack DR Test Trigger": {
                "name": "Slack DR Test Trigger",
                "type": "1",
                "status": "0",
                "exec_path": "send_slack.sh",
                "exec_params": TEST_EXEC_PARAMS,
            },
            "Slack Failback Test": {
                "name": "Slack Failback Test",
                "type": "1",
                "status": "0",
                "exec_path": "send_failback.sh",
                "exec_params": TEST_EXEC_PARAMS,
            },
        }

    @staticmethod
    def _media_diff(current: dict[str, Any], desired: dict[str, Any]) -> dict[str, Any]:
        fields = ("name", "type", "status", "exec_path", "exec_params")
        return {field: desired[field] for field in fields if current.get(field) != desired[field]}

    def _desired_filter(self, state: dict[str, Any], plan: Plan) -> dict[str, Any] | None:
        missing = [name for name, host in state["hosts"].items() if host is None]
        if missing:
            plan.errors.append("missing test host(s): " + ", ".join(missing))
            return None
        return {
            "evaltype": "2",
            "conditions": [
                {"conditiontype": "1", "operator": "0", "value": _text(state["hosts"][name]["hostid"])}
                for name in self.host_names
            ],
        }

    def _user_media_plan(
        self,
        state: dict[str, Any],
        media_ids: dict[str, str],
        plan: Plan,
    ) -> None:
        user = state["user"]
        if user is None:
            plan.errors.append(f"recipient user {self.settings.recipient_username!r} is missing")
            return
        existing = [_copy(item) for item in user.get("medias") or []]
        proposed = _copy(existing)
        for name in TEST_MEDIA_NAMES:
            media_id = media_ids[name]
            matches = [item for item in proposed if _text(item.get("mediatypeid")) == media_id]
            if len(matches) > 1:
                plan.errors.append(f"recipient has duplicate test media {media_id}")
                continue
            expected = {
                "mediatypeid": media_id,
                "sendto": "slack",
                "active": "0",
                "severity": "63",
                "period": "1-7,00:00-24:00",
            }
            if not matches:
                proposed.append(expected)
                plan.changes.append(f"add {name} to {self.settings.recipient_username}")
                continue
            current = matches[0]
            if any(_text(current.get(key)) != value for key, value in expected.items() if key != "mediatypeid"):
                current.update({key: value for key, value in expected.items() if key != "mediatypeid"})
                plan.changes.append(f"update {name} for {self.settings.recipient_username}")
        if proposed != existing:
            plan.user_media = proposed

    def _action_plan(self, state: dict[str, Any], plan: Plan, desired_status: str | None) -> None:
        action = state["action"]
        if desired_status == "1" and action is None:
            return
        media_ids = {
            name: _text(item.get("mediatypeid"))
            for name, item in state["media"].items()
            if item is not None
        }
        if any(name not in media_ids for name in TEST_MEDIA_NAMES):
            plan.errors.append("test media dependencies are not available")
            return
        user = state["user"]
        if user is None:
            plan.errors.append(f"recipient user {self.settings.recipient_username!r} is missing")
            return
        user_id = _text(user.get("userid"))
        desired_filter = self._desired_filter(state, plan)
        if desired_filter is None:
            return
        desired_operations = [_operation(media_ids["Slack DR Test Trigger"], user_id)]
        desired_recovery = [_recovery_operation(media_ids["Slack Failback Test"], user_id)]
        if action is None:
            if desired_status != "0":
                return
            plan.action_create = {
                "name": TEST_ACTION_NAME,
                "eventsource": "0",
                "status": "0",
                "esc_period": "1h",
                "filter": desired_filter,
                "operations": desired_operations,
                "recovery_operations": desired_recovery,
            }
            plan.changes.append(f"create action {TEST_ACTION_NAME}")
            return

        if _text(action.get("eventsource")) != "0":
            plan.errors.append(f"{TEST_ACTION_NAME} exists but is not a trigger action")
            return
        if action.get("update_operations"):
            plan.errors.append(f"{TEST_ACTION_NAME} has unrelated update operations")
            return
        current_operations = action.get("operations") or []
        current_recovery = action.get("recovery_operations") or []
        if len(current_operations) > 1 or len(current_recovery) > 1:
            plan.errors.append(f"{TEST_ACTION_NAME} has unexpected extra operations")
            return
        update: dict[str, Any] = {}
        if _test_filter_signature(action.get("filter")) != _test_filter_signature(desired_filter):
            update["filter"] = desired_filter
            plan.changes.append(f"update {TEST_ACTION_NAME} host filter")
        if _text(action.get("esc_period")) != "1h":
            update["esc_period"] = "1h"
            plan.changes.append(f"update {TEST_ACTION_NAME} escalation period")
        if desired_status is not None and _text(action.get("status")) != desired_status:
            update["status"] = desired_status
            plan.changes.append(
                f"{'enable' if desired_status == '0' else 'disable'} {TEST_ACTION_NAME}"
            )
        desired_operation = desired_operations[0]
        if not current_operations or _operation_signature(current_operations[0]) != _operation_signature(desired_operation):
            update["operations"] = desired_operations
            plan.changes.append(f"update {TEST_ACTION_NAME} Problem operation")
        desired_recovery_operation = desired_recovery[0]
        if not current_recovery or _recovery_operation_signature(current_recovery[0]) != _recovery_operation_signature(desired_recovery_operation):
            update["recovery_operations"] = desired_recovery
            plan.changes.append(f"update {TEST_ACTION_NAME} Recovery operation")
        if update:
            plan.action_update = (_text(action.get("actionid")), update)

    def build_plan(self, state: dict[str, Any], desired_status: str | None) -> Plan:
        plan = Plan()
        specs = self._media_specs()
        media_ids = {}
        for name, desired in specs.items():
            current = state["media"].get(name)
            if current is None:
                if desired_status == "0":
                    plan.media_creates.append(desired)
                    plan.changes.append(f"create media type {name}")
            else:
                media_ids[name] = _text(current.get("mediatypeid"))
                differences = self._media_diff(current, desired)
                if differences:
                    plan.media_updates.append((_text(current.get("mediatypeid")), differences))
                    plan.changes.append(f"update media type {name}: {', '.join(differences)}")

        if desired_status == "0":
            if len(media_ids) == len(TEST_MEDIA_NAMES):
                self._user_media_plan(state, media_ids, plan)
            else:
                plan.changes.append("bind test user media after media creation")
                return plan
        self._action_plan(state, plan, desired_status)
        return plan

    def apply_plan(self, plan: Plan) -> None:
        if plan.errors:
            raise ConfigurationError("; ".join(plan.errors))
        for spec in plan.media_creates:
            self.api.call("mediatype.create", spec)
        for media_id, fields in plan.media_updates:
            self.api.call("mediatype.update", {"mediatypeid": media_id, **fields})

        state = self.inspect()
        refreshed = self.build_plan(state, "0")
        if refreshed.errors:
            raise ConfigurationError("; ".join(refreshed.errors))
        if refreshed.user_media is not None:
            self.api.call(
                "user.update",
                {
                    "userid": _text(state["user"].get("userid")),
                    "medias": _writable_user_medias(refreshed.user_media),
                },
            )

        state = self.inspect()
        refreshed = self.build_plan(state, "0")
        if refreshed.errors:
            raise ConfigurationError("; ".join(refreshed.errors))
        if refreshed.action_create:
            self.api.call("action.create", refreshed.action_create)
        if refreshed.action_update:
            action_id, payload = refreshed.action_update
            self.api.call("action.update", {"actionid": action_id, **payload})

    def set_disabled(self, state: dict[str, Any]) -> None:
        action = state.get("action")
        if action is None or _text(action.get("status")) == "1":
            return
        self.api.call("action.update", {"actionid": _text(action["actionid"]), "status": "1"})

    def snapshot(self, state: dict[str, Any], api_version: str) -> dict[str, Any]:
        return {
            "exported_at": api_version,
            "action_name": TEST_ACTION_NAME,
            "hosts": [_redact(state["hosts"].get(name)) for name in self.host_names],
            "media_types": [_redact(state["media"].get(name)) for name in TEST_MEDIA_NAMES],
            "action": _redact(state["action"]),
            "user": _redact(state["user"]),
        }


def _print_plan(plan: Plan) -> None:
    for change in plan.changes:
        print(f"DRIFT: {change}")
    for error in plan.errors:
        print(f"BLOCKED: {error}")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--enable", action="store_true", help="create/reconcile and enable the test action")
    mode.add_argument("--disable", action="store_true", help="disable the test action without deleting it")
    parser.add_argument("--check", action="store_true", help="read-only inspection (default)")
    parser.add_argument("--expect", choices=("on", "off"), help="expected state for --check")
    parser.add_argument("--env-file", help="external file containing Zabbix API settings")
    parser.add_argument(
        "--host",
        action="append",
        dest="test_hosts",
        help="exact visible Zabbix host name to include; repeat for additional hosts",
    )
    parser.add_argument(
        "--backup-dir",
        type=Path,
        default=Path("/var/lib/hospital-dr/zabbix-config-backups"),
        help="external directory for redacted pre-change exports",
    )
    args = parser.parse_args(argv)
    try:
        settings = load_settings(args.env_file)
        values = _read_env_file(Path(args.env_file)) if args.env_file else {}
        raw_hosts = values.get("ZABBIX_DR_TEST_HOSTS", "")
        configured_hosts = tuple(item.strip() for item in raw_hosts.split(",") if item.strip())
        if args.test_hosts:
            host_names = tuple(dict.fromkeys((*configured_hosts, *args.test_hosts)))
        else:
            host_names = configured_hosts or DEFAULT_TEST_HOSTS
        if len(set(host_names)) != len(host_names):
            raise ConfigurationError("ZABBIX_DR_TEST_HOSTS contains duplicate host names")
        client = ZabbixClient(settings)
        version = client.authenticate()
        configurator = BroadTestConfigurator(client, settings, host_names)
        state = configurator.inspect()
        action = state.get("action")
        current_status = "on" if action is not None and _text(action.get("status")) == "0" else "off"
        print(f"TEST_ACTION={TEST_ACTION_NAME}")
        print(f"TEST_HOSTS={','.join(host_names)}")
        print(f"TEST_MODE={current_status.upper()}")

        if args.disable:
            if action is not None:
                backup_dir = args.backup_dir
                timestamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
                backup = backup_dir / f"zabbix-broad-test-pre-disable-{timestamp}.json"
                _write_json_atomic(backup, configurator.snapshot(state, version))
                print(f"BACKUP PASS: {backup}")
                configurator.set_disabled(state)
            final = configurator.inspect()
            final_status = "on" if final.get("action") is not None and _text(final["action"].get("status")) == "0" else "off"
            if final_status != "off":
                raise ConfigurationError("test action remained enabled after --disable")
            print("TEST MODE DISABLED")
            return 0

        desired_status = "0" if args.enable else None
        plan = configurator.build_plan(state, desired_status)
        _print_plan(plan)
        if args.enable:
            if plan.errors:
                print("ENABLE BLOCKED")
                return 1
            if plan.changes:
                timestamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
                backup = args.backup_dir / f"zabbix-broad-test-pre-enable-{timestamp}.json"
                _write_json_atomic(backup, configurator.snapshot(state, version))
                print(f"BACKUP PASS: {backup}")
                configurator.apply_plan(plan)
            final = configurator.inspect()
            final_plan = configurator.build_plan(final, "0")
            if final_plan.errors or final_plan.changes or final.get("action") is None or _text(final["action"].get("status")) != "0":
                _print_plan(final_plan)
                raise ConfigurationError("post-enable verification failed")
            print("TEST MODE ENABLED")
            return 0

        if plan.errors:
            return 1
        if args.expect and current_status != args.expect:
            print(f"EXPECTATION FAILED: TEST_MODE={current_status.upper()} expected={args.expect.upper()}")
            return 2
        if action is None:
            print("CHECK DRIFT: test action is not configured")
            return 2
        if plan.changes:
            print("CHECK DRIFT: no changes were made")
            return 2
        print("CHECK PASS: broad test action configuration is present")
        return 0
    except Exception as exc:
        # Keep API and file errors concise; never print settings or payloads.
        print(f"ERROR: {type(exc).__name__}: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
